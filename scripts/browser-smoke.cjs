const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const path = require('node:path');
const fs = require('node:fs');
const crypto = require('node:crypto');
const project = path.resolve(__dirname, '..');
const root = project;
const evidence = process.env.EVIDENCE_DIR || path.join(project, 'evidence');
const baseUrl = process.env.BASE_URL || 'http://127.0.0.1:8080';
const sampleDir = process.env.SAMPLE_DIR || path.join(project, 'samples');
fs.mkdirSync(evidence, {recursive:true});
(async () => {
 const browser = await chromium.launch({executablePath:process.env.BROWSER_EXECUTABLE || undefined, headless:true});
 const context = await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
 const page = await context.newPage();
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const checks=[];
 const mark = s => {checks.push(s); console.log(s)};
 try {
  await page.goto(baseUrl);
  await page.getByRole('button',{name:'新建核对',exact:true}).first().click();
  await page.getByLabel('上传左表',{exact:true}).setInputFiles({name:'malformed.csv',mimeType:'text/csv',buffer:Buffer.from('id,x\nA,"unclosed')});
  await page.getByRole('alert').waitFor();
  if (await page.getByLabel('上传左表',{exact:true}).count()!==1) throw Error('Failed import was shown as usable');
  mark('Malformed CSV shows an error and preserves usable upload controls');
  await page.getByLabel('关闭错误提示').click();
  await page.getByLabel('上传左表',{exact:true}).setInputFiles(path.join(sampleDir,'left-orders.csv'));
  await page.getByText('left-orders.csv',{exact:true}).first().waitFor();
  await page.getByLabel('上传右表',{exact:true}).setInputFiles(path.join(sampleDir,'right-payments.csv'));
  await page.getByRole('button',{name:'下一步：确认字段'}).click();
  await page.getByLabel('左表主键',{exact:true}).selectOption('c1');
  await page.getByLabel('右表主键',{exact:true}).selectOption('c1');
  await page.getByLabel('第1组左表字段',{exact:true}).selectOption('c3');
  await page.getByLabel('第1组右表字段',{exact:true}).selectOption('c3');
  await page.getByLabel('第1组比较类型',{exact:true}).selectOption('decimal');
  await page.getByRole('checkbox').check();
  await page.getByRole('button',{name:'确认并核对'}).click();
  await page.getByRole('heading',{name:'核对结果',exact:true}).waitFor({timeout:60000});
  await page.locator('.results-table tbody tr').nth(8).waitFor();
  if(await page.locator('.results-table tbody tr').count()!==9)throw Error('Expected 9 result groups');
  mark('Real browser upload -> mapping confirmation -> computed results: 9 groups');
  await page.screenshot({path:path.join(evidence,'results-desktop.png'),fullPage:true});
  await page.getByRole('row').filter({hasText:'ORD-008'}).getByRole('button',{name:'查看来源'}).click();
  await page.getByRole('dialog').waitFor();
  if (await page.getByLabel('关闭来源详情').evaluate(element => element !== document.activeElement)) throw Error('Source drawer did not receive keyboard focus');
  const detail=await page.getByRole('dialog').innerText();
  if(!detail.includes('9007199254740993.01') || !detail.includes('9007199254740993.02') || !detail.includes('0.01'))throw Error('Exact decimal evidence missing');
  mark('Source drawer shows both exact large decimals and difference 0.01');
  await page.screenshot({path:path.join(evidence,'source-detail.png'),fullPage:false});
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({state:'hidden'});
  mark('Source drawer focus and Escape keyboard dismissal work');
  await page.locator('.status-filters').getByRole('button',{name:/存在差异/}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.results-table tbody tr').length===2);
  mark('Changed status filter shows exactly two groups');
  const dl=page.waitForEvent('download');
  await page.getByRole('button',{name:'导出全部结果'}).click();
  const file=await dl;
  await file.saveAs(path.join(evidence,'browser-export.xlsx'));
  const hash=crypto.createHash('sha256').update(fs.readFileSync(path.join(evidence,'browser-export.xlsx'))).digest('hex');
  mark('Actual XLSX download saved');
  await page.reload();
  await page.getByRole('button',{name:'核对历史',exact:true}).click();
  await page.getByRole('button',{name:'查看',exact:true}).first().click();
  await page.getByRole('heading',{name:'核对结果',exact:true}).waitFor();
  await page.locator('.results-table tbody tr').nth(8).waitFor();
  mark('Refresh -> persistent history -> original results restored');
  const dl2=page.waitForEvent('download');
  await page.getByRole('button',{name:'导出全部结果'}).click();
  const file2=await dl2; await file2.saveAs(path.join(evidence,'browser-export-repeat.xlsx'));
  if(hash!==crypto.createHash('sha256').update(fs.readFileSync(path.join(evidence,'browser-export-repeat.xlsx'))).digest('hex'))throw Error('Repeated export hash changed');
  mark('Repeated export bytes identical after refresh');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(evidence,'results-mobile.png'),fullPage:true});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+2))throw Error('Mobile page overflows horizontally');
  mark('390px viewport has no page-level horizontal overflow');
  if(errors.length)throw Error(errors.join('\n'));
  fs.writeFileSync(path.join(evidence,'browser-checks.json'),JSON.stringify({status:'PASS',checked_at:new Date().toISOString(),origin:baseUrl,runtime:process.env.RUNTIME_DESCRIPTION || 'Native Windows PostgreSQL + FastAPI + Vite; not Docker',checks,export_sha256:hash,page_errors:errors},null,2));
 } catch(e) {
  await page.screenshot({path:path.join(evidence,'browser-failure.png'),fullPage:true});
  console.error((await page.locator('body').innerText()).slice(0,4500));
  throw e;
 } finally {await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
